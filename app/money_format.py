def format_money(amount, currency) -> str:
    """'1590' + 'GBP' -> '£1,590.00'. Unknown codes fall back to 'XYZ 1,590.00'; bad amounts to ''."""
    if amount is None or amount == '':
        return ''
    try:
        value = Decimal(str(amount))
    except (InvalidOperation, ValueError):
        return ''
    code = (currency or '').strip().upper()
    digits = MINOR_UNITS.get(code, 2)
    value = value.quantize(Decimal(1).scaleb(-digits), rounding=ROUND_HALF_UP)
    number = f'{abs(value):,.{digits}f}'
    prefix = CURRENCY_PREFIXES.get(code, f'{code} ' if code else '')
    return f"{'-' if value < 0 else ''}{prefix}{number}"
